#!/usr/bin/env python3
"""Generate the public Markdown resume from the existing site content."""

import argparse
import json
from html.parser import HTMLParser
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}


class Element:
    def __init__(self, tag, attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def text(self):
        return " ".join("".join(child.text() if isinstance(child, Element) else child
                                for child in self.children).split())

    def find(self, tag=None, **attrs):
        matches = []
        for child in self.children:
            if isinstance(child, Element):
                if (tag is None or child.tag == tag) and all(
                    child.attrs.get(key.rstrip("_")) == value for key, value in attrs.items()
                ):
                    matches.append(child)
                matches.extend(child.find(tag, **attrs))
        return matches

    def one(self, tag=None, **attrs):
        matches = self.find(tag, **attrs)
        if len(matches) != 1:
            raise ValueError(f"Expected one element for {tag}, {attrs}; found {len(matches)}")
        return matches[0]


class ResumeHTML(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.root = Element("document")
        self.stack = [self.root]
        self.feed(source)
        self.close()

    def handle_starttag(self, tag, attrs):
        node = Element(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in VOID_TAGS:
            self.stack.append(node)

    def handle_endtag(self, tag):
        if tag not in VOID_TAGS:
            if self.stack[-1].tag != tag:
                raise ValueError(f"Unexpected closing tag: {tag}")
            self.stack.pop()

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def generate():
    page = ResumeHTML((ROOT / "index.html").read_text(encoding="utf-8")).root
    projects = json.loads((ROOT / "projects.json").read_text(encoding="utf-8"))
    intro = page.one(id="intro").one(class_="hero-copy")
    domain = (ROOT / "CNAME").read_text(encoding="utf-8").strip()
    lines = ["<!-- Generated by scripts/generate_resume.py from index.html and projects.json. -->",
             "", "# " + intro.one("h1").text(), "",
             f"웹 이력서: https://{domain}/", ""]
    for heading in intro.find("h2"):
        lines.extend([heading.text(), ""])
    for paragraph in intro.find("p"):
        lines.extend([paragraph.text(), ""])

    for section_id, item_tag in [("skills", "article"), ("tech", "div")]:
        section = page.one(id=section_id)
        lines.extend(["## " + section.one("h2").text(), ""])
        for scope in section.find(class_="scope-copy"):
            for paragraph in scope.find("p"):
                lines.extend([paragraph.text(), ""])
        container = section.one(class_="skill-grid" if section_id == "skills" else "tech-groups")
        for item in container.find(item_tag):
            lines.append(f"- **{item.one('h3').text()}:** {item.one('p').text()}")
        lines.append("")

    lines.extend(["## " + page.one(id="projects").one("h2").text(), "", projects["note"], ""])
    for project in projects["projects"]:
        lines.extend(["### " + project["title"], "", project["subtitle"], "",
                      "분야: " + " · ".join(project["tags"]), ""])
        if project["technologies"]:
            lines.extend(["사용 기술: " + " · ".join(project["technologies"]), ""])
        for entry in project["evidence"]:
            lines.append(f"- **{entry['label']}:** {entry['text']}")
        lines.append("")

    contact = page.one(id="contact")
    lines.extend(["## " + contact.one("h2").text(), ""])
    for link in contact.one(class_="footer-links").find("a"):
        lines.append(f"- [{link.text()}]({link.attrs['href']})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if resume.md needs regeneration")
    args = parser.parse_args()
    generated = generate()
    target = ROOT / "resume.md"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != generated:
            parser.exit(1, "resume.md is out of date. Run: python3 scripts/generate_resume.py\n")
        print("resume.md matches the public site content.")
    else:
        target.write_text(generated, encoding="utf-8")
        print("Generated resume.md")
